// Counted:  a point in time during the last 10 days of January 2025
// Recorded: 2026-09-26. The 2026 edition is not published yet, so this is current.
//
// CA-500 is the HUD Continuum of Care code for Santa Clara County. If you came
// here looking for "CA-16": that is a California congressional district, not a
// HUD identifier, and HUD publishes nothing under it.
//
// DERIVED DATA. Do not hand edit. To refresh for 2026:
//   1. Check whether CoC_HIC_CoC_CA-500-2026_CA_2026.pdf exists.
//   2. Re-extract the Emergency Shelter, Safe Haven and Transitional Housing
//      sections only. Permanent Supportive Housing, Rapid Re-Housing and Other
//      Permanent Housing are deliberately excluded: those are program
//      placements made through coordinated entry, not doors a person can walk
//      to tonight. Listing them as shelters would send someone toward a
//      building they cannot enter.
//   3. Update the dates above and in lib/listings/sources.ts.
//
// WHAT THIS SOURCE DOES NOT PUBLISH, and which therefore stays null on every
// row rather than being guessed:
//   pets, pet weight limit, couples, ID requirement, curfew, check-in window,
//   max stay, phone, street address, latitude and longitude.
// See sourceCovers in lib/listings/sources.ts. Rather than showing a blank, the
// UI tells the person to call Here4You at (408) 385-2400, which is how county
// shelter intake actually works.
//
// TWO FURTHER LIMITATIONS, both coming from HUD's own file:
//
//   Bed counts are NOT recorded here. The published PDF's text layer glues
//   adjacent numeric columns together ("110" is an 11 and a 0), so per column
//   figures cannot be separated reliably. A wrong bed count is worse than no
//   bed count. Staff can enter real counts through the portal.
//
//   Facility names are often TRUNCATED by HUD ("Mountain View Nightly Shelt",
//   "HDAP Bella Vista Interim Ho"). They are kept verbatim rather than guessed
//   at. The truncated flag marks the ones visibly cut off.
//
// city is set only where the provider or facility name states it. A null city
// is shown county wide rather than assigned to a city we cannot confirm.
//
// confidential marks domestic violence programs. Their locations are
// deliberately not public. Never publish an address or coordinates for these,
// and route them through the DV path rather than ordinary intake.

